"""Simulated bank alert emails for demos and testing (disabled in production).

Builds a realistic credit/debit alert from one of the user's own banks and sends it to
their connected Gmail inbox over SMTP. The regular Gmail sync then picks it up and
turns it into a transaction, exactly like a real alert would be.
"""

import asyncio
import random
import uuid
from datetime import datetime, timedelta, timezone
from decimal import Decimal

from sqlalchemy import select

from app.core.config import settings
from app.core.db import scoped_session
from app.core.mailer import send_email
from app.models import Bank, BankAccount, Card, EmailConnection
from app.services import gmail

PKT = timezone(timedelta(hours=5))

DEBITS = [
    ("KFC DHA PHASE 6", 1200, 3800), ("FOODPANDA", 900, 3200), ("IMTIAZ SUPER MARKET", 3500, 12000),
    ("CARREFOUR PAKISTAN", 4000, 15000), ("PSO SERVICE STATION", 3000, 7000), ("SHELL CLIFTON", 3000, 6500),
    ("D WATSON", 600, 4500), ("KHAADI DOLMEN MALL", 3500, 11000), ("DARAZ PK", 1500, 9000),
    ("CAREEM", 350, 1200), ("CHEEZIOUS", 1100, 3500), ("NAHEED SUPERMARKET", 2500, 9000),
]
CREDITS = [
    ("IBFT FROM AHMED RAZA", 2000, 25000), ("RAAST TRANSFER FROM SARA KHAN", 1500, 15000),
    ("REFUND DARAZ PK", 800, 5000), ("CASHBACK REWARD", 200, 1500),
]


class TestAlertError(RuntimeError):
    pass


def _amount(low: int, high: int) -> Decimal:
    return Decimal(random.randrange(low, high, 10))


def build_alert(bank: Bank, account: BankAccount, card: Card | None, direction: str) -> tuple[str, str, str, dict]:
    when = datetime.now(PKT)
    stamp = when.strftime("%d-%b-%Y %H:%M")
    ref = random.randint(100000000, 999999999)
    if direction == "debit":
        merchant, low, high = random.choice(DEBITS)
        amount = _amount(low, high)
        balance = Decimal(account.balance) - amount
        via = f"{card.network.title()} card ****{card.last4}" if card and card.last4 else f"A/C ****{account.last4 or '0000'}"
        line = f"PKR {amount:,.2f} has been debited from your {via} at {merchant} on {stamp}."
    else:
        merchant, low, high = random.choice(CREDITS)
        amount = _amount(low, high)
        balance = Decimal(account.balance) + amount
        line = f"PKR {amount:,.2f} has been credited to your A/C ****{account.last4 or '0000'} via {merchant} on {stamp}."
    subject = f"{gmail.TEST_ALERT_SUBJECT}: {bank.name} {'Debit' if direction == 'debit' else 'Credit'} Alert"
    text = (
        f"Dear Customer,\n\n{line}\nAvailable Balance PKR {balance:,.2f}.\nTransaction Ref: {ref}\n\n"
        f"If you did not perform this transaction, call {bank.short_name} helpline immediately.\n\n"
        f"-- This is a simulated alert generated by {settings.app_name} for testing. No real money moved. --"
    )
    html = f"""
    <div style="font-family:Arial,sans-serif;max-width:520px;margin:auto;border:1px solid #ddd;border-radius:12px;overflow:hidden">
      <div style="background:#224F10;color:#EAFFD0;padding:14px 18px;font-weight:bold">{bank.name} · Transaction Alert</div>
      <div style="padding:18px;color:#0D0D0D;line-height:1.5">
        <p>Dear Customer,</p><p>{line}<br>Available Balance PKR {balance:,.2f}.</p>
        <p style="color:#666;font-size:12px">Transaction Ref: {ref}</p>
        <p style="color:#999;font-size:11px">Simulated alert generated by {settings.app_name} for testing. No real money moved.</p>
      </div>
    </div>"""
    return subject, text, html, {"bank": bank.name, "direction": direction, "amount": float(amount), "merchant": merchant}


async def send_test_alert(user_id: uuid.UUID) -> dict:
    if not settings.test_tools_enabled:
        raise TestAlertError("test_tools_disabled")
    if not settings.smtp_username or not settings.smtp_password:
        raise TestAlertError("smtp_not_configured")
    async with scoped_session(user_id, "user") as s:
        conns = list((await s.execute(select(EmailConnection).where(EmailConnection.status == "active"))).scalars())
        if not conns:
            raise TestAlertError("connect_gmail_first")
        accounts = list((await s.execute(select(BankAccount, Bank).join(Bank, Bank.id == BankAccount.bank_id))).all())
        if not accounts:
            raise TestAlertError("add_a_bank_first")
        account, bank = random.choice(accounts)
        card = await s.scalar(select(Card).where(Card.account_id == account.id).limit(1))
        direction = "debit" if random.random() < 0.7 else "credit"
        subject, text, html, info = build_alert(bank, account, card, direction)
        targets = [(c.id, c.email_address) for c in conns]
    sent = [address for _, address in targets if await send_email(address, subject, text, html)]
    if not sent:
        raise TestAlertError("send_failed")
    # Pick it up quickly instead of waiting for the regular poll.
    asyncio.get_running_loop().create_task(_sync_soon(user_id, [cid for cid, _ in targets]))
    return {**info, "sent_to": sent}


async def _sync_soon(user_id: uuid.UUID, conn_ids: list[uuid.UUID]) -> None:
    for delay in (12, 30):
        await asyncio.sleep(delay)
        for cid in conn_ids:
            try:
                if await gmail.sync_connection(cid, user_id):
                    return
            except Exception:  # noqa: BLE001 - best effort, the scheduler retries
                pass
